//! End-to-end tests for protocol verification proc macros.
//!
//! VERIFICATION LEVEL: VERIFY
//! Tests that `#[trust_vc::protocol]`, `#[trust_vc::action]`, `#[trust_vc::safety]`
//! generate correct registration code and verify through the ty pipeline.
//!
//! Requires the `ty` feature: `targo --unverified test -p trust-vc --features ty`

#![cfg(feature = "ty")]

mod common;

use trust_vc_core::verification_bridge::{
    register_protocol_action, register_protocol_invariant, VerificationPipeline,
};
use trust_vc_core::VerifyResult;

// --- Protocol struct with macro-generated registration ---

#[trust_vc::protocol]
#[derive(Default)]
struct BoundedCounter {
    x: u8,
}

#[trust_vc::protocol]
#[derive(Default)]
struct SimpleMutex {
    in_cs1: bool,
    in_cs2: bool,
}

/// Protocol macro expansion must preserve ordinary Rust struct behavior so test
/// targets stay warning-clean under repo-wide cargo checks.
#[test]
fn test_protocol_macro_types_remain_plain_rust_structs() {
    let counter = BoundedCounter { x: 0 };
    let mutex = SimpleMutex {
        in_cs1: false,
        in_cs2: false,
    };

    assert_eq!(counter.x, 0, "protocol macro should preserve field access");
    assert!(
        !mutex.in_cs1 && !mutex.in_cs2,
        "protocol macro should preserve multi-field access"
    );
}

/// Test that `#[trust_vc::protocol]` generates a working `__trust_vc_register_protocol()`.
/// The generated method registers state vars in the thread-local registry,
/// enabling `VerificationPipeline::collect_from_macros()` to assemble protocol
/// obligations.
#[test]
fn test_protocol_macro_generates_registration() {
    common::with_clean_verification(|| {
        // Generated by #[trust_vc::protocol] — registers state vars
        BoundedCounter::__trust_vc_register_protocol();

        // Manually register action + invariant (action/safety macros need
        // function call context; here we test the protocol struct path)
        register_protocol_action(
            "BoundedCounter",
            "Increment",
            "{ if self.x >= 5 { return; } self.x = self.x + 1 }",
        );
        register_protocol_invariant("BoundedCounter", "Bounded", "{ self.x <= 5 }");

        let pipeline = VerificationPipeline::collect_from_macros();
        let result = pipeline.verify();
        assert!(
            matches!(result, VerifyResult::Verified),
            "Bounded counter via macro registration should verify, got: {result:?}"
        );
    });
}

/// Test protocol macro registration with multi-field struct.
#[test]
fn test_protocol_macro_multi_field_registration() {
    common::with_clean_verification(|| {
        SimpleMutex::__trust_vc_register_protocol();

        register_protocol_action(
            "SimpleMutex",
            "Enter1",
            "{ if self.in_cs2 { return; } self.in_cs1 = true }",
        );
        register_protocol_action("SimpleMutex", "Leave1", "{ self.in_cs1 = false }");
        register_protocol_action(
            "SimpleMutex",
            "Enter2",
            "{ if self.in_cs1 { return; } self.in_cs2 = true }",
        );
        register_protocol_action("SimpleMutex", "Leave2", "{ self.in_cs2 = false }");
        register_protocol_invariant(
            "SimpleMutex",
            "MutualExclusion",
            "{ self.in_cs1 == false || self.in_cs2 == false }",
        );

        let pipeline = VerificationPipeline::collect_from_macros();
        let result = pipeline.verify();
        assert!(
            matches!(result, VerifyResult::Verified),
            "Mutex via macro registration should verify mutual exclusion, got: {result:?}"
        );
    });
}

/// Negative test: protocol macro registration + invariant violation.
#[test]
fn test_protocol_macro_invariant_violation() {
    common::with_clean_verification(|| {
        BoundedCounter::__trust_vc_register_protocol();

        // Unbounded increment — no guard
        register_protocol_action("BoundedCounter", "Increment", "{ self.x = self.x + 1 }");
        register_protocol_invariant("BoundedCounter", "Bounded", "{ self.x <= 5 }");

        let pipeline = VerificationPipeline::collect_from_macros();
        let result = pipeline.verify();
        assert!(
            !matches!(result, VerifyResult::Verified),
            "Unbounded counter should find invariant violation"
        );
    });
}
