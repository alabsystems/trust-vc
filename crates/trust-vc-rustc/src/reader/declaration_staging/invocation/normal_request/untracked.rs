//! Explicit handling of the installed compiler's untracked native options.
//!
//! The expected values are from the live producer Invocation, never a saved
//! receipt or argv digest. The owned binder cannot request different residual
//! settings. Typed equality rejects differences even where rustc deliberately
//! excludes a field from dependency tracking. The parent separately checks all
//! represented request differences against actual Session/CStore facts.
//!
//! Each exhaustive census pattern deliberately omits `..`: adding a compiler option requires
//! reviewing this boundary even if the new option would be ignored by rustc's
//! tracking hash. See the source packet's installed-options-census.json.

use super::super::rustc_session::config::{
    CodegenOptions, JsonUnusedExterns, Options, UnstableOptions,
};

macro_rules! same_fields {
    ($actual:expr, $expected:expr, $prefix:literal; $($field:ident),+ $(,)?) => {
        $(if $actual.$field != $expected.$field {
            return Err(concat!("the actual normal untracked native option ", $prefix,
                stringify!($field), " differs from the genuine producer baseline").into());
        })+
    };
}

