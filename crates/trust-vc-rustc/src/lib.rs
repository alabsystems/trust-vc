//! trust-vc-rustc: the rustc side of trust-vc's Verus front end.
//!
//! Upstream Verus's test harness runs `target-verus/<profile>/rust_verify` on
//! each test program. This crate provides that binary. It expands the program
//! with upstream's `verus!` macros (built by trustc), reads the result out of
//! rustc into VcIR (`trust-vc-vcir`), and reports per-function verdicts as
//! rustc JSON diagnostics on stderr, which is the only channel the harness
//! reads.
//!
//! Modules:
//!   * [`args`]: splits the harness argv into Verus options and rustc
//!     arguments (rustc-free).
//!   * [`verdict`]: the verdict record and the refusal diagnostic format
//!     (rustc-free).
//!   * [`verus_items`]: the Verus diagnostic items the reader matches by
//!     definition (rustc-free).
//!   * [`vtyp`]: types as Verus spells them in diagnostics (rustc-free).
//!   * [`messages`]: Verus's message texts and checking phases (rustc-free).
//!   * `reader` (feature `rustc`): HIR and type-check results lowered into
//!     VcIR.
//!   * `verify` (feature `rustc`): the read crate's checks, generated by
//!     trust-vc-vcir and answered by trust-vc-core, reported as Verus
//!     reports them.
//!   * `shim` (feature `rustc`): the compiler callbacks and the entry point of
//!     the `rust_verify` binary.
//!   * `metadata_inspect` (feature `rustc`): foreign declaration observations
//!     without granting import, mode/header or proof authority.
//!   * `declaration_observe` (feature `rustc`): local Keep-body declaration
//!     observations before a separate authentication/alignment step.

