    #[test]
    fn test_lean_export_syntactically_valid_basics() {
        let t = trace(vec![cl(1, &[1]), cl(2, &[-1])], vec![rs(3, 1, 1, 2)], 3);
        let lean = export_lean5(&t).expect("export should succeed");

        // No unclosed parentheses or angle brackets (basic balance check)
        let open_angle: usize = lean.chars().filter(|&c| c == '\u{27e8}').count();
        let close_angle: usize = lean.chars().filter(|&c| c == '\u{27e9}').count();
        assert_eq!(open_angle, close_angle, "angle brackets should be balanced");

        // Every `by` keyword appears on a line with `theorem` or `proof_valid`
        // and is followed by `decide` on the next line
        let lines: Vec<&str> = lean.lines().collect();
        for (i, line) in lines.iter().enumerate() {
            if line.trim_start().starts_with("decide") {
                // The preceding non-empty line should end with `:= by`
                let prev = (0..i)
                    .rev()
                    .find(|&j| !lines[j].trim().is_empty())
                    .expect("decide should have a preceding line");
                assert!(
                    lines[prev].ends_with(":= by"),
                    "decide at line {} should follow a ':= by' line, but found: {}",
                    i + 1,
                    lines[prev]
                );
            }
        }

        // No double blank lines (style check)
        assert!(!lean.contains("\n\n\n"), "should not have triple newlines");

        // Ends with a newline
        assert!(lean.ends_with('\n'), "output should end with newline");
    }

