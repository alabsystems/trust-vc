    #[test]
    fn test_lean_export_roundtrip_structure_validation() {
        // Export a non-trivial proof and parse the Lean5 output to validate
        // that every structural element appears with correct syntax.
        let t = ProofTrace {
            input_clauses: vec![cl(1, &[1, 2]), cl(2, &[-1, 3]), cl(3, &[-2]), cl(4, &[-3])],
            resolution_steps: vec![
                rs(5, 1, 1, 2), // resolve {1,2} and {-1,3} on pivot 1 -> {2,3}
                rs(6, 2, 5, 3), // resolve {2,3} and {-2} on pivot 2 -> {3}
                rs(7, 3, 6, 4), // resolve {3} and {-3} on pivot 3 -> {}
            ],
            theory_lemmas: vec![],
            empty_clause_id: 7,
        };
        let lean = export_lean5(&t).expect("export should succeed");

        // Count structural elements: exactly 4 `def clause_` definitions
        let def_count = lean
            .lines()
            .filter(|l| l.starts_with("def clause_"))
            .count();
        assert_eq!(
            def_count, 4,
            "should have exactly 4 input clause definitions"
        );

        // Exactly 3 resolution theorems
        let theorem_count = lean
            .lines()
            .filter(|l| l.starts_with("theorem resolution_step_"))
            .count();
        assert_eq!(
            theorem_count, 3,
            "should have exactly 3 resolution step theorems"
        );

        // Exactly 1 proof_valid theorem
        let proof_valid_count = lean
            .lines()
            .filter(|l| l.starts_with("theorem proof_valid"))
            .count();
        assert_eq!(
            proof_valid_count, 1,
            "should have exactly 1 proof_valid theorem"
        );

        // Every `theorem` line must end with `:= by`
        for line in lean.lines() {
            if line.starts_with("theorem ") {
                assert!(
                    line.ends_with(":= by"),
                    "theorem line should end with ':= by', got: {line}"
                );
            }
        }

        // Every `def clause_` line must contain angle-bracketed list
        for line in lean.lines() {
            if line.starts_with("def clause_") {
                assert!(
                    line.contains('\u{27e8}') && line.contains('\u{27e9}'),
                    "clause def should use angle brackets, got: {line}"
                );
            }
        }

        // No axiom declarations (no theory lemmas in this trace)
        assert!(
            !lean.contains("axiom "),
            "should have no axiom declarations without theory lemmas"
        );
    }

    #[test]
    fn test_lean_export_theory_lemma_mixed_with_resolution() {
        // A proof where a theory lemma participates in resolution.
        // Input: {1}
        // Theory lemma (EUF): {-1, 2}
        // Theory lemma (LRA): {-2}
        // Resolution step 1: resolve cl(1) and tl(10) on pivot 1 -> clause_20 = {2}
        // Resolution step 2: resolve clause_20 and tl(11) on pivot 2 -> clause_21 = {}
        let t = ProofTrace {
            input_clauses: vec![cl(1, &[1])],
            resolution_steps: vec![rs(20, 1, 1, 10), rs(21, 2, 20, 11)],
            theory_lemmas: vec![
                TheoryLemma {
                    id: 10,
                    theory: "EUF".into(),
                    clause: cl(10, &[-1, 2]),
                },
                TheoryLemma {
                    id: 11,
                    theory: "LRA".into(),
                    clause: cl(11, &[-2]),
                },
            ],
            empty_clause_id: 21,
        };
        let lean = export_lean5(&t).expect("export should succeed");

        // Input clause defined
        assert!(lean.contains("def clause_1 : Clause := \u{27e8}[1]\u{27e9}"));

        // Theory lemma clauses defined
        assert!(lean.contains("def clause_10 : Clause := \u{27e8}[(-1), 2]\u{27e9}"));
        assert!(lean.contains("def clause_11 : Clause := \u{27e8}[(-2)]\u{27e9}"));

        // Both theory axioms present with correct theory annotations
        assert!(lean.contains("axiom theory_lemma_10_valid : True"));
        assert!(lean.contains("-- Theory: EUF (trusted)"));
        assert!(lean.contains("axiom theory_lemma_11_valid : True"));
        assert!(lean.contains("-- Theory: LRA (trusted)"));

        // Resolution steps correctly reference theory lemma clause IDs
        assert!(lean.contains("resolves clause_1 clause_10 1 clause_20"));
        assert!(lean.contains("resolves clause_20 clause_11 2 clause_21"));

        // Final proof
        assert!(lean.contains("Clause.isEmpty clause_21"));
    }
