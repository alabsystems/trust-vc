        let prelude_pos = lean.find("abbrev Literal := Int").expect("prelude missing");
        let input_pos = lean
            .find("-- Input clauses")
            .expect("input clauses section missing");
        let theory_pos = lean
            .find("-- Theory lemmas (trusted axioms)")
            .expect("theory lemmas section missing");
        let resolution_pos = lean
            .find("-- Resolution steps")
            .expect("resolution steps section missing");
