//! Lean5 proof term export.
//!
//! Converts a [`ProofTrace`] resolution proof into a Lean5 source file that
//! encodes the propositional resolution derivation as decidable `by decide`
//! proof terms. Theory lemmas are emitted as trusted `axiom` declarations
//! because their correctness depends on external theory solvers.
//!
//! The generated Lean5 code is self-contained and can be checked by `lean`
//! to independently verify the UNSAT derivation.

use std::fmt::Write as _;

use crate::types::{ClauseId, LiteralId, ProofTrace};

// ---------------------------------------------------------------------------
// Error type
// ---------------------------------------------------------------------------

/// Errors that can occur during Lean5 export.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum LeanExportError {
    /// The proof trace has no input clauses.
    #[error("proof trace has no input clauses")]
    EmptyTrace,

    /// The empty clause ID does not match any clause or resolution step.
    #[error("empty clause ID {0} not found in proof trace")]
    EmptyClauseNotFound(ClauseId),

    /// A formatting error occurred while building the Lean5 output.
    #[error("formatting error: {0}")]
    Fmt(#[from] std::fmt::Error),
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/// Export a [`ProofTrace`] as a Lean5 proof term.
///
/// The output is a self-contained Lean5 source file encoding:
/// - Input clauses as `def` declarations
/// - Theory lemmas as trusted `axiom` declarations
/// - Resolution steps as `theorem` declarations with `by decide` proofs
/// - A final `theorem proof_valid` tying the derivation together
///
/// # Errors
///
/// Returns [`LeanExportError`] if the trace is empty or structurally invalid.
#[must_use = "exported Lean5 source should be consumed"]
pub fn export_lean5(trace: &ProofTrace) -> Result<String, LeanExportError> {
    validate_trace(trace)?;

    let mut out = String::new();

    write_header(&mut out)?;
    write_prelude(&mut out)?;
    write_input_clauses(&mut out, trace)?;
    write_theory_lemmas(&mut out, trace)?;
    write_resolution_steps(&mut out, trace)?;
    write_proof_valid(&mut out, trace)?;

    Ok(out)
}

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

/// Validate that the trace is structurally suitable for export.
fn validate_trace(trace: &ProofTrace) -> Result<(), LeanExportError> {
    if trace.input_clauses.is_empty() && trace.theory_lemmas.is_empty() {
        return Err(LeanExportError::EmptyTrace);
    }

    // Verify the empty clause ID is reachable.
    let found = trace
        .input_clauses
        .iter()
        .any(|c| c.id == trace.empty_clause_id)
        || trace
            .theory_lemmas
            .iter()
            .any(|tl| tl.id == trace.empty_clause_id)
        || trace
            .resolution_steps
            .iter()
            .any(|s| s.id == trace.empty_clause_id);

    if !found {
        return Err(LeanExportError::EmptyClauseNotFound(trace.empty_clause_id));
    }

    Ok(())
}

// ---------------------------------------------------------------------------
// Lean5 generation helpers
// ---------------------------------------------------------------------------

/// Write the auto-generated header with metadata comments.
fn write_header(out: &mut String) -> Result<(), LeanExportError> {
    writeln!(out, "-- Auto-generated by trust-vc-kernel")?;
    writeln!(
        out,
        "-- Proof that the negation of the verification condition is unsatisfiable"
    )?;
    writeln!(out, "--")?;
    writeln!(out, "-- trust_vc version: 1.0.0")?;
    writeln!(out, "-- generator: trust-vc-kernel::lean_export")?;
    writeln!(out)?;
    Ok(())
}

/// Write the Lean5 prelude defining the `Clause` structure and resolution predicates.
fn write_prelude(out: &mut String) -> Result<(), LeanExportError> {
    writeln!(out, "-- Prelude: clause representation and resolution")?;
    writeln!(out)?;
    writeln!(out, "abbrev Literal := Int")?;
    writeln!(out)?;
    writeln!(out, "structure Clause where")?;
    writeln!(out, "  lits : List Literal")?;
    writeln!(out, "deriving Repr, DecidableEq")?;
    writeln!(out)?;
    writeln!(out, "def negLit (l : Literal) : Literal := -l")?;
    writeln!(out)?;
    writeln!(out, "/-- A clause is empty (contains no literals). -/")?;
    writeln!(out, "def Clause.isEmpty (c : Clause) : Prop := c.lits = []")?;
    writeln!(out)?;
    writeln!(
        out,
        "instance : Decidable (Clause.isEmpty c) := inferInstanceAs (Decidable (c.lits = []))"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/-- Resolution: resolving clause `a` and clause `b` on pivot `p`"
    )?;
    writeln!(out, "    produces clause `r`, where `r.lits` equals")?;
    writeln!(
        out,
        "    `(a.lits.filter (· != p)) ++ (b.lits.filter (· != negLit p))`. -/"
    )?;
    writeln!(
        out,
        "def resolves (a b : Clause) (p : Literal) (r : Clause) : Prop :="
    )?;
    writeln!(
        out,
        "  r.lits = (a.lits.filter (· != p)) ++ (b.lits.filter (· != negLit p))"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "instance : Decidable (resolves a b p r) := inferInstanceAs (Decidable (_ = _))"
    )?;
    writeln!(out)?;
    writeln!(out, "-- End prelude")?;
    writeln!(out)?;
    Ok(())
}

/// Format a list of literals as a Lean5 list literal.
fn format_literal_list(lits: &[LiteralId]) -> String {
    let items: Vec<String> = lits.iter().map(|l| format_literal(*l)).collect();
    format!("[{}]", items.join(", "))
}

/// Format a single literal for Lean5. Negative literals need parentheses.
fn format_literal(lit: LiteralId) -> String {
    if lit < 0 {
        format!("({lit})")
    } else {
        format!("{lit}")
    }
}

/// Write input clause definitions.
fn write_input_clauses(out: &mut String, trace: &ProofTrace) -> Result<(), LeanExportError> {
    if trace.input_clauses.is_empty() {
        return Ok(());
    }

    writeln!(out, "-- Input clauses")?;
    writeln!(out)?;

    for clause in &trace.input_clauses {
        let lit_list = format_literal_list(&clause.literals);
        writeln!(
            out,
            "def clause_{} : Clause := \u{27e8}{}\u{27e9}",
            clause.id, lit_list
        )?;
    }

    writeln!(out)?;
    Ok(())
}

/// Write theory lemma declarations as trusted axioms.
fn write_theory_lemmas(out: &mut String, trace: &ProofTrace) -> Result<(), LeanExportError> {
    if trace.theory_lemmas.is_empty() {
        return Ok(());
    }

    writeln!(out, "-- Theory lemmas (trusted axioms)")?;
    writeln!(
        out,
        "-- These clauses were produced by theory solvers (EUF, LRA, BV, etc.)"
    )?;
    writeln!(
        out,
        "-- and are accepted without propositional proof. Their soundness"
    )?;
    writeln!(
        out,
        "-- depends on the correctness of the ay-dpll theory solvers."
    )?;
    writeln!(out)?;

    for lemma in &trace.theory_lemmas {
        let lit_list = format_literal_list(&lemma.clause.literals);
        writeln!(
            out,
            "def clause_{} : Clause := \u{27e8}{}\u{27e9}",
            lemma.id, lit_list
        )?;
        writeln!(out, "-- Theory: {} (trusted)", lemma.theory)?;
        writeln!(out, "axiom theory_lemma_{}_valid : True", lemma.id)?;
        writeln!(out)?;
    }

    Ok(())
}

/// Write resolution step theorems.
fn write_resolution_steps(out: &mut String, trace: &ProofTrace) -> Result<(), LeanExportError> {
    if trace.resolution_steps.is_empty() {
        return Ok(());
    }

    writeln!(out, "-- Resolution steps")?;
    writeln!(out)?;

    for (i, step) in trace.resolution_steps.iter().enumerate() {
        let pivot_str = format_literal(step.pivot);
        writeln!(
            out,
            "theorem resolution_step_{} : resolves clause_{} clause_{} {} clause_{} := by",
            i + 1,
            step.parent1,
            step.parent2,
            pivot_str,
            step.id
        )?;
        writeln!(out, "  decide")?;
        writeln!(out)?;
    }

    Ok(())
}

/// Write the final `proof_valid` theorem asserting the empty clause is derived.
fn write_proof_valid(out: &mut String, trace: &ProofTrace) -> Result<(), LeanExportError> {
    writeln!(out, "-- Final proof: the empty clause has been derived")?;
    writeln!(out)?;
    writeln!(
        out,
        "theorem proof_valid : Clause.isEmpty clause_{} := by",
        trace.empty_clause_id
    )?;
    writeln!(out, "  decide")?;

    Ok(())
}

