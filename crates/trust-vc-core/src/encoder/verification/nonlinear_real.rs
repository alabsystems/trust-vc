/// Outcome of the nonlinear-real certificate search.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) enum NonlinearRealOutcome {
    /// A sound certificate established the implication. Safe to report
    /// `Verified` to the caller.
    Proven,
    /// No certificate found, or the assertion is outside the supported
    /// fragment. The caller must fall through to the ordinary solver — this
    /// pass never reports failure on its own.
    NotEstablished,
}

/// A monomial of total degree at most 2 over the canonical variable indices.
///
/// Represented as a sorted list of variable indices (with repetition encoding
/// powers): `[]` is the constant `1`, `[i]` is `x_i`, `[i, i]` is `x_i^2`,
/// `[i, j]` (`i <= j`) is `x_i * x_j`.
type Monomial = Vec<u32>;

/// A multivariate polynomial of total degree at most 2: a map from monomial to
/// rational coefficient. Zero coefficients are never stored.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct Poly {
    terms: BTreeMap<Monomial, Rational>,
}

impl Poly {
    fn zero() -> Self {
        Self {
            terms: BTreeMap::new(),
        }
    }

    fn constant(c: Rational) -> Self {
        let mut p = Self::zero();
        if !c.is_zero() {
            p.terms.insert(Vec::new(), c);
        }
        p
    }

    fn var(idx: u32) -> Self {
        let mut p = Self::zero();
        p.terms.insert(vec![idx], Rational::one());
        p
    }

    /// Total degree of the polynomial (0 for the zero polynomial).
    fn degree(&self) -> usize {
        self.terms.keys().map(Vec::len).max().unwrap_or(0)
    }

    fn add_assign(&mut self, other: &Poly) {
        for (mono, coeff) in &other.terms {
            self.add_term(mono.clone(), coeff.clone());
        }
    }

    fn add_term(&mut self, mono: Monomial, coeff: Rational) {
        if coeff.is_zero() {
            return;
        }
        let entry = self
            .terms
            .entry(mono.clone())
            .or_insert_with(Rational::zero);
        *entry = entry.add(&coeff);
        // Drop the term if it canceled, so zero/equality checks stay canonical
        // (a polynomial is zero iff its term map is empty).
        if entry.is_zero() {
            self.terms.remove(&mono);
        }
    }

    fn add(&self, other: &Poly) -> Poly {
        let mut out = self.clone();
        out.add_assign(other);
        out
    }

    fn sub(&self, other: &Poly) -> Poly {
        let mut out = self.clone();
        for (mono, coeff) in &other.terms {
            out.add_term(mono.clone(), coeff.neg());
        }
        out
    }

    fn neg(&self) -> Poly {
        let mut out = Poly::zero();
        for (mono, coeff) in &self.terms {
            out.terms.insert(mono.clone(), coeff.neg());
        }
        out
    }

    fn scale(&self, factor: &Rational) -> Poly {
        if factor.is_zero() {
            return Poly::zero();
        }
        let mut out = Poly::zero();
        for (mono, coeff) in &self.terms {
            out.terms.insert(mono.clone(), coeff.mul(factor));
        }
        out
    }

    /// Multiply two polynomials. Returns `None` if the product would exceed
    /// the supported total degree [`MAX_DEGREE`].
    ///
    /// Degree 3 is admitted only so the division-rule equality shape
    /// `q * D == N` (with `D`, `N` of degree 2 and `q` linear) can be parsed;
    /// all *certificate* reasoning happens on degree-2 sub-polynomials. Any
    /// genuinely degree-3 target is rejected by the SOS check (fail-closed).
    fn mul(&self, other: &Poly) -> Option<Poly> {
        let mut out = Poly::zero();
        for (m1, c1) in &self.terms {
            for (m2, c2) in &other.terms {
                if m1.len() + m2.len() > MAX_DEGREE {
                    return None;
                }
                let mut mono = m1.clone();
                mono.extend_from_slice(m2);
                mono.sort_unstable();
                out.add_term(mono, c1.mul(c2));
            }
        }
        Some(out)
    }
}

/// A normalized atomic constraint `poly {kind} 0`.
#[derive(Debug, Clone)]
struct Atom {
    poly: Poly,
    kind: AtomKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AtomKind {
    /// `poly >= 0`
    Ge,
    /// `poly > 0`
    Gt,
    /// `poly == 0`
    Eq,
}

/// Public entry point: attempt to discharge a `by(nonlinear_arith)` real
/// degree-2 implication. Never reports failure — only `Proven` (certificate
/// found) or `NotEstablished` (fall through).
pub(super) fn try_prove_nonlinear_real(expr: &TrustVcExpr) -> NonlinearRealOutcome {
    let Some(problem) = parse_problem(expr) else {
        return NonlinearRealOutcome::NotEstablished;
    };
    if problem.prove() {
        NonlinearRealOutcome::Proven
    } else {
        NonlinearRealOutcome::NotEstablished
    }
}

/// Convenience wrapper returning an [`AssertionOutcome`] when proven, or `None`
/// when the caller should fall through to the ordinary solver.
pub(super) fn try_prove_nonlinear_real_outcome(expr: &TrustVcExpr) -> Option<AssertionOutcome> {
    match try_prove_nonlinear_real(expr) {
        NonlinearRealOutcome::Proven => Some(AssertionOutcome::Verified),
        NonlinearRealOutcome::NotEstablished => None,
    }
}

/// Verus-faithful DEFAULT-prover boundary for nonlinear REAL arithmetic.
///
/// Verus runs its default SMT queries with Z3's nonlinear arithmetic switched
/// **off** (`smt.arith.nl=false`); nonlinear real reasoning is only available
/// under an explicit `by(nonlinear_arith)` hint. That hint discipline is a
/// deliberate, observable semantic of the Verus proof language: upstream
/// `real.rs::real_nonlinear2` asserts a TRUE nonlinear-real fact hint-free and
/// EXPECTS it to fail ("This is true, but we expect that it requires
/// nonlinear_arith"). Since ay's NRA interval branch-and-prune lane
/// (ay 43034c4b0c) the bare ay procedure can decide such facts, which would
/// silently diverge from Verus on the unhinted path — the exact leak the
/// `is_nonlinear_arith_mode` dispatch comment in assertion.rs warns about,
/// materializing inside ay instead of inside trust-vc.
///
/// This detector walks an obligation's goal expression and reports the first
/// real-sorted nonlinear construct:
///   * a product of two non-constant real-typed terms, or
///   * a division/remainder by a non-constant real-typed divisor.
///
/// The unhinted verification path refuses to submit such a goal to the solver
/// and classifies it as genuine theory INCOMPLETENESS — a model-less
/// verification failure per `design-unknown-as-failure.md`, exactly how
/// Verus surfaces the same query (`Invalid(None, None, None)`). Products with
/// a compile-time-constant factor and divisions by constants remain linear and
/// pass through untouched.
///
/// Residual (sound, fail-closed) capability gap, documented on purpose: a goal
/// that Z3-with-`arith.nl=false` could still prove by treating the product as
/// an opaque term (e.g. a product appearing only in a hypothesis of a linear
/// goal, or `x*y == x*y` by congruence) is also refused here. No ported corpus
/// case has that shape; if a future port does, the row fails visibly at port
/// time — it can never verify unsoundly.
pub(super) fn unhinted_nonlinear_real_construct(expr: &TrustVcExpr) -> Option<&'static str> {
    use crate::ir_expr_traversal::{walk_expr, TrustVcExprVisitor};

    struct Finder {
        found: Option<&'static str>,
    }
    impl TrustVcExprVisitor for Finder {
        fn visit_expr(&mut self, expr: &TrustVcExpr) {
            if self.found.is_some() {
                return;
            }
            if let TrustVcExpr::Arith {
                op,
                left,
                right,
                ty,
            } = expr
            {
                if is_real_ty(ty) {
                    match op {
                        ArithOp::Mul
                            if !is_compile_time_constant(left)
                                && !is_compile_time_constant(right) =>
                        {
                            self.found = Some("a product of two non-constant real-typed terms");
                            return;
                        }
                        ArithOp::Div | ArithOp::Rem if !is_compile_time_constant(right) => {
                            self.found = Some("a division by a non-constant real-typed divisor");
                            return;
                        }
                        _ => {}
                    }
                }
            }
            walk_expr(self, expr);
        }
    }

    let mut finder = Finder { found: None };
    finder.visit_expr(expr);
    finder.found
}

/// Compile-time-constant numeric subtree: numeric literals and Min/Max
/// constants combined with arithmetic, negation, and numeric casts. Anything
/// mentioning a variable, call, index, or collection is non-constant.
fn is_compile_time_constant(expr: &TrustVcExpr) -> bool {
    match expr {
        TrustVcExpr::IntLit { .. } | TrustVcExpr::IntConst { .. } => true,
        TrustVcExpr::Neg(inner) => is_compile_time_constant(inner),
        TrustVcExpr::Arith { left, right, .. } => {
            is_compile_time_constant(left) && is_compile_time_constant(right)
        }
        TrustVcExpr::Cast { expr, .. } => is_compile_time_constant(expr),
        _ => false,
    }
}

/// A parsed problem: hypotheses plus a single goal atom, over a fixed variable
/// indexing.
struct Problem {
    hypotheses: Vec<Atom>,
    goal: Atom,
    /// Index of the goal variable, if the goal is a bare variable sign
    /// condition `x {>=,>} 0`. Enables the division rule.
    goal_var: Option<u32>,
}

/// Parse a `TrustVcExpr` into a [`Problem`]. Returns `None` whenever the
/// expression is outside the supported fragment (any failure is silent and
/// fail-closed: the caller falls through to the solver).
fn parse_problem(expr: &TrustVcExpr) -> Option<Problem> {
    let mut vars: Vec<String> = Vec::new();

    let (premise, conclusion) = match expr {
        TrustVcExpr::Implies {
            premise,
            conclusion,
        } => (Some(premise.as_ref()), conclusion.as_ref()),
        // Implication normalized to disjunctive form `!premise || conclusion`.
        // The encoder/lowering may present `P ==> Q` as `!(P) || Q`, so accept
        // that shape too. Exactly one disjunct must be a `Not(premise)`.
        TrustVcExpr::Logic {
            op: crate::ir_expr::LogicOp::Or,
            left,
            right,
        } => match (negated_premise(left), negated_premise(right)) {
            (Some(prem), None) => (Some(prem), right.as_ref()),
            (None, Some(prem)) => (Some(prem), left.as_ref()),
            // `!P || !R` or `R || S` (no negation): not an implication shape.
            _ => return None,
        },
        // A bare conclusion with no premise is also allowed.
        other => (None, other),
    };

    let mut hypotheses = Vec::new();
    if let Some(premise) = premise {
        collect_conjuncts(premise, &mut hypotheses, &mut vars)?;
    }

    let goal = parse_atom(conclusion, &mut vars)?;

    // Determine whether the goal is a bare-variable sign condition `x {>=,>} 0`
    // (after normalization), to enable the single-variable division rule.
    let goal_var = bare_var_sign_goal(&goal);

    Some(Problem {
        hypotheses,
        goal,
        goal_var,
    })
}

/// If the goal is `x {>=,>} 0` (positive unit coefficient on a single
/// variable, no other terms), return that variable index.
fn bare_var_sign_goal(goal: &Atom) -> Option<u32> {
    if goal.kind == AtomKind::Eq {
        return None;
    }
    if goal.poly.terms.len() != 1 {
        return None;
    }
    let (mono, coeff) = goal.poly.terms.iter().next()?;
    if mono.len() == 1 && coeff.is_one() {
        Some(mono[0])
    } else {
        None
    }
}

/// If `expr` is `!(premise)`, return the inner premise. Used to recognize the
/// disjunctive-normal-form encoding of an implication `!P || Q`.
fn negated_premise(expr: &TrustVcExpr) -> Option<&TrustVcExpr> {
    match expr {
        TrustVcExpr::Not(inner) => Some(inner.as_ref()),
        _ => None,
    }
}

/// Recursively collect conjuncts of an `&&` chain into atomic hypotheses.
fn collect_conjuncts(
    expr: &TrustVcExpr,
    out: &mut Vec<Atom>,
    vars: &mut Vec<String>,
) -> Option<()> {
    match expr {
        TrustVcExpr::Logic {
            op: crate::ir_expr::LogicOp::And,
            left,
            right,
        } => {
            collect_conjuncts(left, out, vars)?;
            collect_conjuncts(right, out, vars)?;
            Some(())
        }
        other => {
            let atom = parse_atom(other, vars)?;
            out.push(atom);
            Some(())
        }
    }
}

/// Parse a single comparison atom, normalizing to `poly {kind} 0`.
fn parse_atom(expr: &TrustVcExpr, vars: &mut Vec<String>) -> Option<Atom> {
    let TrustVcExpr::Compare { op, left, right } = expr else {
        return None;
    };
    let lp = parse_real_poly(left, vars)?;
    let rp = parse_real_poly(right, vars)?;
    let diff = lp.sub(&rp); // left - right
                            // Normalize comparison to `<expr> {kind} 0`.
    let (poly, kind) = match op {
        // left >= right  ->  (left - right) >= 0
        CompareOp::Ge => (diff, AtomKind::Ge),
        // left > right   ->  (left - right) > 0
        CompareOp::Gt => (diff, AtomKind::Gt),
        // left <= right  ->  (right - left) >= 0
        CompareOp::Le => (diff.neg(), AtomKind::Ge),
        // left < right   ->  (right - left) > 0
        CompareOp::Lt => (diff.neg(), AtomKind::Gt),
        // left == right  ->  (left - right) == 0
        CompareOp::Eq => (diff, AtomKind::Eq),
        // `!=` does not give a usable sign/equality constraint here.
        CompareOp::Ne => return None,
    };
    // Inequality atoms feed the SOS/cone reasoning, which only handles
    // degree-2 forms, so cap them at degree 2. Equality atoms are allowed up
    // to degree 3 to carry the division-rule shape `q * D == N` (linear in the
    // goal variable, with degree-2 cofactors). `split_linear_in_var` then
    // re-derives degree-2 `D` and `N`; non-linear-in-q equalities are rejected
    // there.
    let max_deg = if kind == AtomKind::Eq { MAX_DEGREE } else { 2 };
    if poly.degree() > max_deg {
        return None;
    }
    Some(Atom { poly, kind })
}

/// Maximum total degree admitted by the polynomial layer. Degree 3 is allowed
/// only to parse the linear-in-`q` division equality shape; all certificate
/// reasoning operates on degree-2 sub-polynomials.
const MAX_DEGREE: usize = 3;

/// Parse a real-typed arithmetic expression into a polynomial of total degree
/// at most [`MAX_DEGREE`]. Returns `None` if the expression is non-polynomial,
/// references a non-real-typed leaf, or would exceed the degree bound.
fn parse_real_poly(expr: &TrustVcExpr, vars: &mut Vec<String>) -> Option<Poly> {
    match expr {
        TrustVcExpr::IntLit { value, ty } => {
            if !is_real_ty(ty) {
                return None;
            }
            Some(Poly::constant(Rational::from_int(*value)))
        }
        TrustVcExpr::Var { name, ty } => {
            if !is_real_ty(ty) {
                return None;
            }
            let idx = intern_var(vars, name);
            Some(Poly::var(idx))
        }
        TrustVcExpr::Neg(inner) => Some(parse_real_poly(inner, vars)?.neg()),
        TrustVcExpr::Arith {
            op,
            left,
            right,
            ty,
        } => {
            if !is_real_ty(ty) {
                return None;
            }
            let lp = parse_real_poly(left, vars)?;
            let rp = parse_real_poly(right, vars)?;
            match op {
                ArithOp::Add => Some(lp.add(&rp)),
                ArithOp::Sub => Some(lp.sub(&rp)),
                ArithOp::Mul => {
                    // `Poly::mul` already rejects products beyond MAX_DEGREE.
                    let prod = lp.mul(&rp)?;
                    Some(prod)
                }
                // Division is only handled for a constant non-zero divisor,
                // which is exact over the rationals.
                ArithOp::Div => {
                    let divisor = rp.as_constant()?;
                    if divisor.is_zero() {
                        return None;
                    }
                    let inv = divisor.inv()?;
                    Some(lp.scale(&inv))
                }
                ArithOp::Rem => None,
            }
        }
        _ => None,
    }
}

impl Poly {
    /// If this polynomial is a rational constant, return it.
    fn as_constant(&self) -> Option<Rational> {
        if self.terms.is_empty() {
            return Some(Rational::zero());
        }
        if self.terms.len() == 1 {
            if let Some(c) = self.terms.get(&Vec::new()) {
                return Some(c.clone());
            }
        }
        None
    }
}

fn is_real_ty(ty: &TrustVcType) -> bool {
    matches!(ty, TrustVcType::Real)
}

/// Intern a variable name to a stable index.
fn intern_var(vars: &mut Vec<String>, name: &str) -> u32 {
    if let Some(idx) = vars.iter().position(|v| v == name) {
        return idx as u32;
    }
    vars.push(name.to_string());
    (vars.len() - 1) as u32
}

impl Problem {
    /// Attempt to prove the goal from the hypotheses using the two sound
    /// deduction rules. Returns `true` only on a found certificate.
    fn prove(&self) -> bool {
        // Rule 1: direct cone membership of the goal polynomial.
        if self.goal_in_cone() {
            return true;
        }
        // Rule 2: single-variable division rule.
        if self.prove_via_division() {
            return true;
        }
        false
    }

    /// Rule 1: is the goal polynomial `Q` (with goal kind `>=` or `>`) a
    /// member of the non-negative cone generated by the hypotheses?
    ///
    /// We try to write `Q = c0 + sum(lambda_i * Hge_i) + sum(squares)
    /// + delta * E` for nonneg `c0`, `lambda_i` over a small integer grid,
    /// nonneg square coefficients, and equality multipliers `delta`. Because
    /// solving the general linear feasibility is heavier than needed for the
    /// target fragment, we use the structured division rule (Rule 2) for the
    /// `q*D=N` shape and reserve Rule 1 for goals that are *literally* a
    /// non-negative combination already present (e.g. `a*a + b*b >= 0`).
    fn goal_in_cone(&self) -> bool {
        if self.goal.kind == AtomKind::Eq {
            return false;
        }
        // The strict-vs-nonstrict distinction: `>` requires strict positivity
        // which our structural prover only certifies for explicit positive
        // constants; be conservative and only claim `>=` style memberships
        // here unless the polynomial is a positive constant.
        if self.goal.kind == AtomKind::Gt {
            if let Some(c) = self.goal.poly.as_constant() {
                return c.is_positive();
            }
            // For non-constant strict goals, defer to the division rule.
            return false;
        }
        self.poly_is_nonneg(&self.goal.poly)
    }

    /// Rule 2: division rule for a bare-variable goal `q {>=,>} 0`.
    ///
    /// Find an equality hypothesis `E == 0` that, viewed as a polynomial in
    /// `q`, has the form `q * D - N == 0` with `D` and `N` not involving `q`
    /// (degree in q is exactly 1). Prove `D > 0` and `N >= 0` (or `N > 0` for
    /// a strict goal) from the cone. Then `q = N / D` has the goal sign.
    fn prove_via_division(&self) -> bool {
        let Some(q) = self.goal_var else {
            return false;
        };
        let strict = self.goal.kind == AtomKind::Gt;

        for hyp in &self.hypotheses {
            if hyp.kind != AtomKind::Eq {
                continue;
            }
            // An equality `E == 0` may be used as `E` or `-E` (both are zero),
            // which flips the signs of `D` and `N`. Try both orientations so
            // the divisor `D` can be made positive.
            for oriented in [hyp.poly.clone(), hyp.poly.neg()] {
                let Some((d_poly, n_poly)) = split_linear_in_var(&oriented, q) else {
                    continue;
                };
                // We need q-free D and N (the division rule reasons about the
                // *sign* of q, so D and N must not themselves mention q).
                if poly_mentions_var(&d_poly, q) || poly_mentions_var(&n_poly, q) {
                    continue;
                }
                // D > 0 and N >= 0  =>  q = N/D >= 0.
                // For a strict goal we additionally need N > 0.
                let d_pos = self.poly_is_positive(&d_poly);
                let n_ok = if strict {
                    self.poly_is_positive(&n_poly)
                } else {
                    self.poly_is_nonneg(&n_poly)
                };
                if d_pos && n_ok {
                    return true;
                }
            }
        }
        false
    }

    /// Sound (incomplete) check that `poly >= 0` on the hypothesis region.
    ///
    /// Membership in the cone generated by non-negative constants, `>=`/`>`
    /// hypotheses (with non-negative integer multipliers), pairwise products
    /// of `>=`/`>` hypotheses, and sums of squares — modulo the equality
    /// hypotheses (which can be added with any rational multiplier).
    ///
    /// We search a small bounded grid of multipliers and verify the residual
    /// is an explicit sum of squares plus a non-negative constant.
    fn poly_is_nonneg(&self, poly: &Poly) -> bool {
        self.cone_contains(poly, false)
    }

    /// Sound check that `poly > 0` on the hypothesis region. Same as
    /// `poly_is_nonneg` but requires a strictly-positive constant slack so the
    /// witnessed lower bound is strictly above zero.
    fn poly_is_positive(&self, poly: &Poly) -> bool {
        // Fast path: a positive rational constant is trivially > 0.
        if let Some(c) = poly.as_constant() {
            return c.is_positive();
        }
        self.cone_contains(poly, true)
    }

    /// Core bounded certificate search: can `target` be written as a
    /// non-negative combination of cone generators (plus equality slack)?
    ///
    /// `strict` requires the constant slack of the certificate to be strictly
    /// positive (proving `> 0` rather than `>= 0`).
    fn cone_contains(&self, target: &Poly, strict: bool) -> bool {
        // Build the list of "generator" polynomials known to be >= 0, each of
        // which may be used with a non-negative integer multiplier from a
        // small grid. Equalities contribute generators usable with *any*
        // integer multiplier (both signs).
        let mut nonneg_gens: Vec<Poly> = Vec::new();
        let mut eq_gens: Vec<Poly> = Vec::new();

        for hyp in &self.hypotheses {
            match hyp.kind {
                AtomKind::Ge | AtomKind::Gt => nonneg_gens.push(hyp.poly.clone()),
                AtomKind::Eq => eq_gens.push(hyp.poly.clone()),
            }
        }
        // Pairwise products of non-negative hypotheses are also non-negative,
        // provided they stay within degree 2.
        let base_len = nonneg_gens.len();
        for i in 0..base_len {
            for j in i..base_len {
                if let Some(prod) = nonneg_gens[i].mul(&nonneg_gens[j]) {
                    if prod.degree() <= 2 {
                        nonneg_gens.push(prod);
                    }
                }
            }
        }

        // Small enumeration grid for non-negative multipliers.
        const GRID: &[i64] = &[0, 1, 2];
        // Equality multipliers may be any sign within a small grid.
        const EQ_GRID: &[i64] = &[-2, -1, 0, 1, 2];

        // (1) Pure sum-of-squares fast path (no hypotheses used).
        if residual_is_sos_nonneg(target, strict) {
            return true;
        }

        // (2a) Proportionality check: if `target = lambda * gen` for some
        // rational `lambda >= 0` and a non-negative generator `gen`, then
        // `target >= 0` (or `> 0` if `lambda > 0` and the generator is strict).
        // This captures rational scalings such as `a/2 >= 0` from `a >= 0`.
        for hyp in &self.hypotheses {
            if hyp.kind == AtomKind::Eq {
                continue;
            }
            if let Some(lambda) = proportional_factor(target, &hyp.poly) {
                if lambda.is_positive() || (!strict && lambda.is_zero()) {
                    // `>` target needs both lambda>0 and a strict generator.
                    if !strict || hyp.kind == AtomKind::Gt {
                        return true;
                    }
                }
            }
        }

        // (2b) Cheap single-generator scan: works even at high arity, where the
        // full combinatorial enumeration is skipped. For each generator, try
        // each non-negative multiplier and test whether the residual is an
        // explicit SOS plus non-negative constant. Sound: a single non-negative
        // multiple of a non-negative generator is non-negative.
        for gen in &nonneg_gens {
            for &m in GRID {
                if m == 0 {
                    continue;
                }
                let residual = target.sub(&gen.scale(&Rational::from_int(i128::from(m))));
                if residual_is_sos_nonneg(&residual, strict) {
                    return true;
                }
            }
        }

        // (3) Full bounded enumeration via a single mixed-radix counter across
        // both generator groups, but only when the generator counts are small
        // enough to keep the search terminating quickly. Otherwise fail closed
        // (the cheap paths above already covered the common cases).
        if nonneg_gens.len() > 6 || eq_gens.len() > 2 {
            return false;
        }
        full_enumeration(target, &nonneg_gens, &eq_gens, GRID, EQ_GRID, strict)
    }
}

/// Advance a single mixed-radix counter; returns false when it rolls over.
fn advance_counter(indices: &mut [usize], radix: usize) -> bool {
    for slot in indices.iter_mut() {
        *slot += 1;
        if *slot < radix {
            return true;
        }
        *slot = 0;
    }
    false
}

/// Full bounded enumeration over both multiplier grids using one mixed-radix
/// counter. Sound: every accepted certificate witnesses `target >= 0`
/// (or `> 0` when `strict`).
fn full_enumeration(
    target: &Poly,
    nonneg_gens: &[Poly],
    eq_gens: &[Poly],
    grid: &[i64],
    eq_grid: &[i64],
    strict: bool,
) -> bool {
    let n = nonneg_gens.len();
    let e = eq_gens.len();
    let mut idx_nonneg = vec![0usize; n];
    let mut idx_eq = vec![0usize; e];

    loop {
        let mut combo = Poly::zero();
        for (k, gen) in nonneg_gens.iter().enumerate() {
            let m = grid[idx_nonneg[k]];
            if m != 0 {
                combo.add_assign(&gen.scale(&Rational::from_int(i128::from(m))));
            }
        }
        for (k, gen) in eq_gens.iter().enumerate() {
            let m = eq_grid[idx_eq[k]];
            if m != 0 {
                combo.add_assign(&gen.scale(&Rational::from_int(i128::from(m))));
            }
        }

        let residual = target.sub(&combo);
        if residual_is_sos_nonneg(&residual, strict) {
            return true;
        }

        // Advance nonneg counter; on rollover advance eq counter.
        if !advance_counter(&mut idx_nonneg, grid.len())
            && !advance_counter(&mut idx_eq, eq_grid.len())
        {
            break;
        }
    }
    false
}

/// Test whether `poly` is provably `>= 0` (or `> 0` when `strict`) by being an
/// explicit sum of squares plus a non-negative (positive) constant.
///
/// Recognized non-negative forms (all sound):
///   * a constant `c >= 0` (or `c > 0` for strict),
///   * a single squared monomial term `k * x^2` with `k >= 0`,
///   * `k * x^2 + k * y^2 + ...` (diagonal SOS with non-negative coeffs),
///   * `k*(a*x^2 + 2*b*x*y + c*y^2)` recognized as a non-negative quadratic
///     form when `a >= 0`, `c >= 0`, and `a*c - b^2 >= 0` (PSD 2x2 form),
///     combined additively across variable pairs.
///
/// Anything not recognized returns `false` (fail-closed).
fn residual_is_sos_nonneg(poly: &Poly, strict: bool) -> bool {
    // Extract the constant term.
    let constant = poly
        .terms
        .get(&Vec::new())
        .cloned()
        .unwrap_or_else(Rational::zero);

    // If the polynomial is purely constant, decide directly.
    if poly.terms.iter().all(|(m, _)| m.is_empty()) {
        return if strict {
            constant.is_positive()
        } else {
            !constant.is_negative()
        };
    }

    // There must be no linear terms (a degree-1 term can be made negative) and
    // no terms of degree 3 or higher (the SOS/PSD certificate only covers
    // degree-2 quadratic forms; any higher-degree residual is fail-closed).
    if poly.terms.keys().any(|m| m.len() == 1 || m.len() >= 3) {
        return false;
    }

    // The quadratic part must be a positive-semidefinite form. Collect the
    // symmetric coefficient matrix over the variables that appear.
    if !quadratic_form_is_psd(poly) {
        return false;
    }

    // The non-square remainder is the constant; require it >= 0 (or > 0).
    if strict {
        // Strict positivity from a PSD quadratic part is not guaranteed unless
        // the constant is strictly positive; require it.
        constant.is_positive()
    } else {
        !constant.is_negative()
    }
}

/// Check that the degree-2 part of `poly` forms a positive-semidefinite
/// quadratic form (so it is `>= 0` for all real assignments).
///
/// Builds the symmetric matrix `M` with `M[i][i]` = coeff of `x_i^2` and
/// `M[i][j] = M[j][i] = (coeff of x_i*x_j) / 2`. The form is PSD iff all
/// leading principal minors are `>= 0` AND the matrix is PSD; we verify PSD
/// soundly via Gaussian elimination on the symmetric matrix (LDL^T): the form
/// is PSD iff every pivot is `>= 0` and no negative pivot ever appears with a
/// non-zero row remainder. We implement the standard sound test: a symmetric
/// matrix is PSD iff it admits an LDL^T decomposition with all `D` entries
/// `>= 0` and zero rows handled consistently.
fn quadratic_form_is_psd(poly: &Poly) -> bool {
    // Gather the variables appearing in degree-2 terms.
    let mut var_set: std::collections::BTreeSet<u32> = std::collections::BTreeSet::new();
    for mono in poly.terms.keys() {
        if mono.len() == 2 {
            var_set.insert(mono[0]);
            var_set.insert(mono[1]);
        }
        if mono.len() == 1 {
            // Linear terms already rejected by caller; be defensive.
            return false;
        }
    }
    if var_set.is_empty() {
        // No quadratic terms — the (non-constant) caller path shouldn't reach
        // here, but an all-constant poly is handled earlier. Treat as PSD.
        return true;
    }
    let vars: Vec<u32> = var_set.into_iter().collect();
    let n = vars.len();
    let index_of = |v: u32| vars.iter().position(|&x| x == v).unwrap();

    // Build the symmetric matrix with rational entries (off-diagonals halved).
    let mut m: Vec<Vec<Rational>> = vec![vec![Rational::zero(); n]; n];
    for (mono, coeff) in &poly.terms {
        match mono.len() {
            2 => {
                let (a, b) = (mono[0], mono[1]);
                let ia = index_of(a);
                let ib = index_of(b);
                if ia == ib {
                    // x^2 term: diagonal entry is the coefficient.
                    m[ia][ia] = m[ia][ia].add(coeff);
                } else {
                    // cross term: split symmetrically, halved.
                    let half = coeff.div(&Rational::from_int(2));
                    m[ia][ib] = m[ia][ib].add(&half);
                    m[ib][ia] = m[ib][ia].add(&half);
                }
            }
            0 => {}
            _ => return false,
        }
    }

    matrix_is_psd(&m, n)
}

/// Sound positive-semidefiniteness test for a symmetric rational matrix via
/// symmetric (LDL^T-style) Gaussian elimination.
///
/// Algorithm: process columns left to right. At each pivot:
///
///   * if the pivot is negative, the matrix is not PSD;
///   * if the pivot is zero, the entire remaining row/column must be zero
///     (otherwise not PSD), and we skip elimination for that pivot;
///   * if the pivot is positive, eliminate the rest of the column via the
///     standard Schur-complement update, preserving symmetry.
///
/// The matrix is PSD iff the process completes without encountering a negative
/// pivot or a zero pivot with a non-zero off-diagonal in its row.
#[allow(clippy::needless_range_loop)]
fn matrix_is_psd(matrix: &[Vec<Rational>], n: usize) -> bool {
    let mut m: Vec<Vec<Rational>> = matrix.to_vec();
    for k in 0..n {
        let pivot = m[k][k].clone();
        if pivot.is_negative() {
            return false;
        }
        if pivot.is_zero() {
            // Zero pivot: the rest of the row and column must vanish for PSD.
            for j in (k + 1)..n {
                if !m[k][j].is_zero() || !m[j][k].is_zero() {
                    return false;
                }
            }
            continue;
        }
        // Positive pivot: Schur-complement elimination of the trailing block.
        for i in (k + 1)..n {
            if m[i][k].is_zero() {
                continue;
            }
            let factor = m[i][k].div(&pivot);
            for j in k..n {
                let delta = factor.mul(&m[k][j]);
                m[i][j] = m[i][j].sub(&delta);
            }
        }
    }
    true
}

/// Split a polynomial `p` into `(D, N)` such that `p = q * D - N`, where `q`
/// is the goal variable and `D`, `N` do not necessarily exclude `q` (callers
/// check that separately). Returns `None` if `q` appears with degree > 1 in
/// any monomial.
fn split_linear_in_var(p: &Poly, q: u32) -> Option<(Poly, Poly)> {
    let mut d = Poly::zero(); // coefficient polynomial of q (the multiplier D)
    let mut rest = Poly::zero(); // q-free part
    for (mono, coeff) in &p.terms {
        let q_count = mono.iter().filter(|&&v| v == q).count();
        match q_count {
            0 => rest.add_term(mono.clone(), coeff.clone()),
            1 => {
                // Drop one occurrence of q to get the cofactor monomial.
                let mut cofactor: Monomial = Vec::new();
                let mut dropped = false;
                for &v in mono {
                    if v == q && !dropped {
                        dropped = true;
                        continue;
                    }
                    cofactor.push(v);
                }
                cofactor.sort_unstable();
                d.add_term(cofactor, coeff.clone());
            }
            // q^2 or higher: outside the linear-in-q division rule.
            _ => return None,
        }
    }
    // p = q*D + rest = q*D - N  where N = -rest.
    let n = rest.neg();
    Some((d, n))
}

fn poly_mentions_var(p: &Poly, v: u32) -> bool {
    p.terms.keys().any(|mono| mono.contains(&v))
}

/// If `target == lambda * base` for some rational `lambda`, return `lambda`.
/// Returns `None` when they are not scalar multiples (including the case where
/// one is zero and the other is not, or their monomial supports differ).
fn proportional_factor(target: &Poly, base: &Poly) -> Option<Rational> {
    if base.terms.is_empty() {
        // base == 0: proportional only if target is also 0 (lambda arbitrary;
        // report 0 to mean "non-negative with no strict slack").
        return target.terms.is_empty().then(Rational::zero);
    }
    if target.terms.is_empty() {
        // target == 0 == 0 * base.
        return Some(Rational::zero());
    }
    if target.terms.len() != base.terms.len() {
        return None;
    }
    let mut lambda: Option<Rational> = None;
    for (mono, t_coeff) in &target.terms {
        let b_coeff = base.terms.get(mono)?;
        // b_coeff is never zero (canonical form), so the ratio is well defined.
        let ratio = t_coeff.div(b_coeff);
        match &lambda {
            None => lambda = Some(ratio),
            Some(prev) => {
                if *prev != ratio {
                    return None;
                }
            }
        }
    }
    lambda
}
