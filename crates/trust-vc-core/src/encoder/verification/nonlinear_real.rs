//! Sound, terminating nonlinear-real certificate search for the
//! `by(nonlinear_arith)` degree-2 polynomial-implication lemma shape.
//!
//! Copyright 2026 Andrew Yates
//! SPDX-License-Identifier: Apache-2.0
//! Author: Andrew Yates <andrewyates.name@gmail.com>
//!
//! # What this proves
//!
//! This module recognizes assertions of the form
//!
//! ```text
//! H_1 && H_2 && ... && H_n ==> G
//! ```
//!
//! where every `H_i` and `G` is an atomic comparison between two real-typed
//! polynomial expressions of total degree at most 2, and every variable is
//! `real`. It then runs a *bounded, sound* Positivstellensatz-style
//! certificate search. It returns [`NonlinearRealOutcome::Proven`] **only**
//! when a certificate witnesses the implication; in every other case it
//! returns [`NonlinearRealOutcome::NotEstablished`], which the caller treats
//! as "fall through to the ordinary solver" (fail-closed — never reports a
//! spurious success).
//!
//! # Soundness sketch
//!
//! Every hypothesis is normalized to `P_i {>=,>,=} 0`. The goal is normalized
//! to `Q {>=,>} 0` (a strict/non-strict sign condition on a polynomial `Q`).
//!
//! The cone of *provably non-negative* polynomials generated by the
//! hypotheses contains:
//!   * the constant `c >= 0`,
//!   * `lambda_i * P_i` for every `>=`/`>` hypothesis with `lambda_i >= 0`,
//!   * `mu_ij * P_i * P_j` for two `>=`/`>` hypotheses with `mu_ij >= 0`,
//!   * any square of a linear form (always `>= 0`),
//!   * `delta * E_k` for an equality hypothesis `E_k = 0` with **any**
//!     rational `delta` (since `E_k = 0`, adding `delta*E_k` changes nothing).
//!
//! Any member of this cone is `>= 0` on the hypothesis region. We use two
//! sound deduction rules:
//!
//! 1. **Direct cone membership.** If `Q` itself lies in the cone (is a
//!    non-negative combination as above), then `Q >= 0` follows.
//!
//! 2. **Single-variable division rule.** If the goal is `q {>=,>} 0` for a
//!    *variable* `q`, and an equality hypothesis can be written
//!    `q * D - N = 0` (so `q * D = N`) where `D` is provably `> 0` and `N` is
//!    provably `>= 0` from the cone, then `q = N / D >= 0`. (If additionally
//!    `N > 0`, then `q > 0`.) This is the canonical real "division" lemma
//!    shape used by `real_nonlinear1`.
//!
//! Both rules are individually sound; we only ever claim `Proven` when one of
//! them produces a certificate. The search is bounded (small fixed multiplier
//! enumeration over an integer grid) so it always terminates.

