use std::collections::HashSet;
use std::fs;

use crate::mode::FunctionMode;
use crate::mode_attrs;
use crate::mode_index::{CanonicalFnPath, CrateModeIndex};
use proc_macro2::TokenStream;
use syn::visit::Visit;
use syn::ItemFn;

use super::scan::{locate_unique_module_items, ModeScan};

/// Collects direct unqualified function calls from a block.
pub(super) struct CallCollector {
    pub(super) calls: Vec<String>,
}

impl<'ast> Visit<'ast> for CallCollector {
    #[allow(clippy::indexing_slicing)] // segments[0] guarded by path.path.segments.len() == 1
    fn visit_expr_call(&mut self, call: &'ast syn::ExprCall) {
        if let syn::Expr::Path(path) = &*call.func {
            if path.qself.is_none()
                && path.path.leading_colon.is_none()
                && path.path.segments.len() == 1
            {
                self.calls.push(path.path.segments[0].ident.to_string());
            }
        }
        syn::visit::visit_expr_call(self, call);
    }
}

/// Returns `true` if the function has a `#[test]` attribute.
///
/// Test functions are exempt from inbound exec-caller auditing because the
/// `#[proof]`/`#[spec]` macros generate test-time wrappers that are
/// intentionally callable from exec test harnesses.
pub(super) fn has_test_attr(item: &ItemFn) -> bool {
    item.attrs.iter().any(|attr| {
        let segs: Vec<_> = attr
            .path()
            .segments
            .iter()
            .map(|segment| segment.ident.to_string())
            .collect();
        segs == ["test"] || segs == ["tokio", "test"]
    })
}

/// Finds exec-mode sibling functions that directly call `target_name`.
///
/// Used for inbound exec-caller auditing: when a proof/spec function expands,
/// this detects illegal `exec -> proof/spec` calls in the same module.
///
/// Skips `#[test]` functions — these intentionally call proof/spec functions
/// through the test-time wrapper generated by the trust_vc macros.
///
/// Returns compile errors positioned at the current function's span (since
/// source-scanned spans don't survive through macro output on stable).
///
/// When a `crate_index` is available, also resolves qualified call paths
/// (`self::target`, `super::target`, `crate::mod::target`) to detect
/// mode violations through qualified calls (#2066).
fn find_exec_callers(
    scan: &ModeScan,
    target_name: &str,
    target_mode: FunctionMode,
    items: &[syn::Item],
    error_span: proc_macro2::Span,
    crate_index: Option<&CrateModeIndex>,
    target_module: &[String],
) -> Vec<TokenStream> {
    let mut target_segs = target_module.to_vec();
    target_segs.push(target_name.to_string());
    let target_canonical = CanonicalFnPath(target_segs);

    let mut errors = Vec::new();

    for item in items {
        if let syn::Item::Fn(item_fn) = item {
            let caller_name = item_fn.sig.ident.to_string();
            let caller_mode = scan
                .sibling_modes
                .get(&caller_name)
                .copied()
                .unwrap_or(FunctionMode::Exec);

            if caller_mode != FunctionMode::Exec {
                continue;
            }
            if has_test_attr(item_fn) {
                continue;
            }

            let mut collector = CallCollector { calls: Vec::new() };
            collector.visit_item_fn(item_fn);

            let has_unqualified_call = collector.calls.iter().any(|call| call == target_name);

            let has_qualified_call = if let Some(index) = crate_index {
                let mut path_collector = crate::mode_paths::PathCallCollector::default();
                path_collector.visit_item_fn(item_fn);

                path_collector.calls.iter().any(|call| {
                    if call.is_simple() {
                        return false;
                    }
                    crate::mode_paths::resolve_call_path(call, target_module, index).as_ref()
                        == Some(&target_canonical)
                })
            } else {
                false
            };

            if has_unqualified_call || has_qualified_call {
                errors.push(
                    syn::Error::new(
                        error_span,
                        format!(
                            "exec function `{}` cannot call {} function `{}`",
                            caller_name, target_mode, target_name
                        ),
                    )
                    .to_compile_error(),
                );
            }
        }
    }

    errors
}

/// Finds exec callers by re-parsing the source file from the span.
///
/// Combines `scan_module` results with file re-parsing to locate exec callers.
/// Returns empty vec if the source cannot be parsed.
///
/// Two passes:
/// 1. Same-module scan: checks sibling exec functions for unqualified and
///    qualified calls (via `find_exec_callers_in_items`).
/// 2. Cross-module sweep: when a crate index is available, scans ALL exec
///    functions in the file for qualified calls that resolve to the target.
///    This catches `specs::helper(x)` from a root-level exec function when
///    `helper` lives in `mod specs` (#2066 Slice 3).
pub(super) fn find_exec_callers_from_source(
    scan: &ModeScan,
    target_name: &str,
    target_tokens: &str,
    target_mode: FunctionMode,
    span: proc_macro2::Span,
    crate_index: Option<&CrateModeIndex>,
    target_module: &[String],
) -> Vec<TokenStream> {
    let file_path = match span.local_file() {
        Some(path) => path,
        None => return Vec::new(),
    };
    let source = match fs::read_to_string(&file_path) {
        Ok(source) => source,
        Err(_) => return Vec::new(),
    };
    let parsed = match crate::parse_file_allow_tracked(&source) {
        Ok(file) => file,
        Err(_) => return Vec::new(),
    };

    let mut errors = find_exec_callers_in_items(
        scan,
        target_name,
        target_tokens,
        target_mode,
        &parsed.items,
        span,
        crate_index,
        target_module,
    );

    if let Some(index) = crate_index {
        let mut reported = HashSet::new();
        for error in &errors {
            reported.insert(error.to_string());
        }

        let mut target_segs = target_module.to_vec();
        target_segs.push(target_name.to_string());
        let target_canonical = CanonicalFnPath(target_segs);

        find_cross_module_exec_callers(
            &parsed.items,
            &[],
            index,
            &target_canonical,
            target_name,
            target_mode,
            span,
            &reported,
            &mut errors,
        );
    }

    errors
}

/// Recursively walks all items in the file looking for exec functions that
/// make qualified calls resolving to the target proof/spec function.
///
/// `current_module` tracks the module path for call resolution context.
#[allow(clippy::too_many_arguments)]
fn find_cross_module_exec_callers(
    items: &[syn::Item],
    current_module: &[String],
    index: &CrateModeIndex,
    target_canonical: &CanonicalFnPath,
    target_name: &str,
    target_mode: FunctionMode,
    error_span: proc_macro2::Span,
    already_reported: &HashSet<String>,
    errors: &mut Vec<TokenStream>,
) {
    for item in items {
        match item {
            syn::Item::Fn(item_fn) => {
                let caller_name = item_fn.sig.ident.to_string();
                let caller_mode = mode_attrs::classify_item_fn(item_fn);

                if caller_mode != FunctionMode::Exec {
                    continue;
                }
                if has_test_attr(item_fn) {
                    continue;
                }

                let mut path_collector = crate::mode_paths::PathCallCollector::default();
                path_collector.visit_item_fn(item_fn);

                let calls_target = path_collector.calls.iter().any(|call| {
                    if call.is_simple() {
                        return false;
                    }
                    crate::mode_paths::resolve_call_path(call, current_module, index).as_ref()
                        == Some(target_canonical)
                });

                if calls_target {
                    let error = syn::Error::new(
                        error_span,
                        format!(
                            "exec function `{}` cannot call {} function `{}`",
                            caller_name, target_mode, target_name
                        ),
                    )
                    .to_compile_error();
                    if !already_reported.contains(&error.to_string()) {
                        errors.push(error);
                    }
                }
            }
            syn::Item::Mod(item_mod) => {
                if let Some((_, ref mod_items)) = item_mod.content {
                    let mut child_module = current_module.to_vec();
                    child_module.push(item_mod.ident.to_string());
                    find_cross_module_exec_callers(
                        mod_items,
                        &child_module,
                        index,
                        target_canonical,
                        target_name,
                        target_mode,
                        error_span,
                        already_reported,
                        errors,
                    );
                }
            }
            _ => {}
        }
    }
}

/// Locates the unique module containing the current function and checks for
/// exec callers within that module.
///
/// Ambiguous matches are already reported by `validate_mode`, so this helper
/// returns no additional diagnostics when the module cannot be uniquely found.
#[allow(clippy::too_many_arguments)]
pub(super) fn find_exec_callers_in_items(
    scan: &ModeScan,
    target_name: &str,
    target_tokens: &str,
    target_mode: FunctionMode,
    items: &[syn::Item],
    error_span: proc_macro2::Span,
    crate_index: Option<&CrateModeIndex>,
    target_module: &[String],
) -> Vec<TokenStream> {
    let Some(module_items) = locate_unique_module_items(items, target_name, target_tokens) else {
        return Vec::new();
    };
    find_exec_callers(
        scan,
        target_name,
        target_mode,
        module_items,
        error_span,
        crate_index,
        target_module,
    )
}
